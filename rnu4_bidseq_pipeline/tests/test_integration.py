# ─── Helpers ──────────────────────────────────────────────────────────────────

def _has_tool(name: str) -> bool:
    import shutil
    return shutil.which(name) is not None


SKIP_IF_NO_TOOLS = pytest.mark.skipif(
    not (_has_tool("minimap2") and _has_tool("samtools")),
    reason="minimap2 and samtools required for BAM-level tests",
)


# ─── Full analysis integration (DataFrame-level) ──────────────────────────────

class TestFullAnalysisIntegration:
    """
    Integration tests that use only Python (no external tools).
    Tests the pileup → stats → calls → RENU chain.
    """

    def test_known_psi_sites_recovered(self, rnu4_2_pileup):
        """Known Ψ sites (pos 4, 72, 79) must be called in the 141-nt pileup."""
        from bidseq.deletion_stats import run_deletion_analysis
        from bidseq.pseudoU_caller import call_pseudoU_sites
        from bidseq.reference import annotate_positions

        anns = annotate_positions(RNU4_2_MOCK)
        stats = run_deletion_analysis(
            treated_pileup    = rnu4_2_pileup,
            annotations       = anns,
            min_coverage      = 20,
            min_deletion_rate = 0.10,
            nanopore_bg_prior = 0.06,
        )
        psi = call_pseudoU_sites(stats, known_psi_sites={4, 72, 79})
        called = set(psi["calls"]["position"].tolist())

        # At least 2 of 3 known sites should be called (some variation allowed)
        recovered = {4, 72, 79} & called
        assert len(recovered) >= 2, (
            f"Expected ≥2 known Ψ sites recovered, got: {recovered} "
            f"(all calls: {called})"
        )

    def test_false_positive_rate(self, rnu4_2_pileup):
        """Non-uridine positions should have near-zero false positive rate."""
        from bidseq.deletion_stats import run_deletion_analysis
        from bidseq.reference import annotate_positions

        anns = annotate_positions(RNU4_2_MOCK)
        stats = run_deletion_analysis(
            treated_pileup = rnu4_2_pileup,
            annotations    = anns,
            min_coverage   = 20,
        )
        # Filter to non-T positions
        non_t = stats[stats["ref_base"].isin(["A", "C", "G"])]
        called_non_t = non_t[non_t["confidence"] != "NOISE"]
        fp_rate = len(called_non_t) / max(len(non_t), 1)
        assert fp_rate < 0.05, (
            f"False positive rate at non-T positions: {fp_rate:.1%} (expected < 5%)"
        )

    def test_psi_summary_structure(self, rnu4_2_pileup):
        """The psi_result summary dict must have all expected keys."""
        from bidseq.deletion_stats import run_deletion_analysis
        from bidseq.pseudoU_caller import call_pseudoU_sites
        from bidseq.reference import annotate_positions

        anns = annotate_positions(RNU4_2_MOCK)
        stats = run_deletion_analysis(treated_pileup=rnu4_2_pileup, annotations=anns)
        psi = call_pseudoU_sites(stats, known_psi_sites={4, 72, 79})
        summary = psi["summary"]

        required_keys = [
            "total_calls", "high_confidence_calls", "moderate_calls",
            "low_calls", "known_psi_recovered", "known_psi_total",
            "novel_calls", "called_positions",
        ]
        for key in required_keys:
            assert key in summary, f"Key '{key}' missing from summary"

    def test_renu_tracking_with_het_insertion(self, rnu4_2_pileup):
        """
        The rnu4_2_pileup fixture has ~25% T insertion at pos 64 (het-ish).
        RENU tracker should flag this without crashing (BAM-less unit version).
        """
        from bidseq.renu_tracker import _infer_zygosity

        # Simulate: 125 RENU reads out of 500 total = VAF 0.25
        z = _infer_zygosity(
            vaf=0.25, n_renu=125, min_reads=3, min_vaf=0.02,
            het_low=0.20, het_high=0.70, hom_low=0.85,
        )
        assert z in ("HETEROZYGOUS", "MOSAIC_OR_LOW_SIGNAL"), (
            f"Expected HET or MOSAIC for VAF=0.25, got {z}"
        )

    def test_stats_df_shape(self, rnu4_2_pileup):
        """Output stats DataFrame must have exactly 141 rows for RNU4-2."""
        from bidseq.deletion_stats import run_deletion_analysis
        from bidseq.reference import annotate_positions

        anns = annotate_positions(RNU4_2_MOCK)
        stats = run_deletion_analysis(treated_pileup=rnu4_2_pileup, annotations=anns)
        assert len(stats) == 141, f"Expected 141 rows, got {len(stats)}"

    def test_q_values_are_bounded(self, rnu4_2_pileup):
        """All q-values must be in [0, 1]."""
        from bidseq.deletion_stats import run_deletion_analysis
        from bidseq.reference import annotate_positions

        anns = annotate_positions(RNU4_2_MOCK)
        stats = run_deletion_analysis(treated_pileup=rnu4_2_pileup, annotations=anns)
        assert (stats["q_value"] >= 0).all()
        assert (stats["q_value"] <= 1).all()

    def test_bed_export_parseable(self, rnu4_2_pileup):
        """BED output must be parseable and have correct format."""
        from bidseq.deletion_stats import run_deletion_analysis
        from bidseq.pseudoU_caller import call_pseudoU_sites, calls_to_bed
        from bidseq.reference import annotate_positions

        anns = annotate_positions(RNU4_2_MOCK)
        stats = run_deletion_analysis(treated_pileup=rnu4_2_pileup, annotations=anns)
        psi = call_pseudoU_sites(stats)
        bed = calls_to_bed(psi["calls"], ref_name="RNU4-2")

        for line in bed.splitlines():
            if line.startswith("#") or not line.strip():
                continue
            parts = line.split("\t")
            assert len(parts) == 6
            start, end = int(parts[1]), int(parts[2])
            assert end > start

    def test_report_generation_no_crash(self, rnu4_2_pileup):
        """Report HTML generation should not crash with realistic data."""
        from bidseq.deletion_stats import run_deletion_analysis
        from bidseq.pseudoU_caller import call_pseudoU_sites
        from bidseq.reference import annotate_positions
        from bidseq.renu_tracker import RenuSiteSummary
        from bidseq.report import generate_report

        anns = annotate_positions(RNU4_2_MOCK)
        stats = run_deletion_analysis(treated_pileup=rnu4_2_pileup, annotations=anns)
        psi = call_pseudoU_sites(stats)

        renu = RenuSiteSummary()
        renu.total_reads = 500
        renu.wild_type_reads = 375
        renu.renu_t_ins_reads = 125
        renu.vaf = 0.25
        renu.zygosity = "MOSAIC_OR_LOW_SIGNAL"
        renu.interpretation = "Test interpretation"
        renu.coverage_at_site = 500

        qc_summary = {"coverage": {"mean_coverage": 500, "fraction_covered": 1.0, "pass": True}, "read_filtering": {"total_in": 1000, "total_out": 950}}
        align_stats = {"mapped_reads": 950, "total_reads": 1000, "mapping_rate": 0.95}

        with tempfile.TemporaryDirectory() as tmpdir:
            out = Path(tmpdir) / "test_report.html"
            generate_report(
                sample_name     = "integration_test",
                pileup_df       = rnu4_2_pileup,
                stats_df        = stats,
                psi_result      = psi,
                renu_summary    = renu,
                qc_summary      = qc_summary,
                alignment_stats = align_stats,
                output_path     = out,
            )
            assert out.exists()
            html = out.read_text()
            assert "BID-seq" in html
            assert "RNU4-2" in html or "integration_test" in html
            assert "RENU" in html
